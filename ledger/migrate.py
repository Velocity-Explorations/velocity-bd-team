"""Apply ledger migrations.

    python -m ledger.migrate            apply any ledger/migrations/NNN_*.sql not yet recorded
    python -m ledger.migrate --list     list tables in the database (like psql's backslash-dt)

Each migration runs in one transaction and is recorded in schema_migrations, so a second
run is a no-op. Migrations are additive only (see AGENTS.md). Files may use the token
@@AUTOINCREMENT@@ on an INTEGER PRIMARY KEY column; it becomes the right syntax per dialect.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from ledger.db import database_url, dialect_of, is_sqlite, now_iso, q, rows, tx

MIGRATIONS_DIR = Path(__file__).resolve().parent / "migrations"
MIGRATION_NAME = re.compile(r"^\d{3}_[A-Za-z0-9_]+\.sql$")

DIALECT_TOKENS: dict[str, dict[str, str]] = {
    "sqlite": {"@@AUTOINCREMENT@@": "AUTOINCREMENT"},
    "postgres": {"@@AUTOINCREMENT@@": "GENERATED BY DEFAULT AS IDENTITY"},
}


def migration_files() -> list[Path]:
    files = [p for p in MIGRATIONS_DIR.iterdir() if MIGRATION_NAME.match(p.name)]
    return sorted(files, key=lambda p: p.name)


def statements(sql_text: str, dialect: str) -> list[str]:
    """Strip comment lines, apply dialect tokens, split on semicolons."""
    for token, replacement in DIALECT_TOKENS[dialect].items():
        sql_text = sql_text.replace(token, replacement)
    lines = [ln for ln in sql_text.splitlines() if not ln.lstrip().startswith("--")]
    body = "\n".join(lines)
    return [s.strip() for s in body.split(";") if s.strip()]


def _ensure_registry(conn) -> None:
    q(conn, "CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, applied_at TEXT NOT NULL)")


def applied_versions(conn) -> set[str]:
    _ensure_registry(conn)
    return {r["version"] for r in rows(q(conn, "SELECT version FROM schema_migrations"))}


def apply(url: str | None = None) -> list[str]:
    """Apply pending migrations. Returns the names applied (empty when nothing to do)."""
    url = url or database_url()
    dialect = dialect_of(url)
    applied: list[str] = []
    with tx(url) as conn:
        done = applied_versions(conn)
    for path in migration_files():
        if path.name in done:
            continue
        with tx(url) as conn:
            for stmt in statements(path.read_text(encoding="utf-8"), dialect):
                q(conn, stmt)
            q(conn, "INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)", (path.name, now_iso()))
        applied.append(path.name)
    return applied


def list_tables(url: str | None = None) -> list[str]:
    url = url or database_url()
    with tx(url) as conn:
        if is_sqlite(conn):
            cur = q(conn, "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
        else:
            cur = q(conn, "SELECT table_name AS name FROM information_schema.tables WHERE table_schema = 'public' ORDER BY table_name")
        return [r["name"] for r in rows(cur)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Apply ledger migrations.")
    parser.add_argument("--list", action="store_true", help="list tables instead of migrating")
    args = parser.parse_args(argv)
    url = database_url()
    print(f"DATABASE_URL dialect: {dialect_of(url)}")
    if args.list:
        for name in list_tables(url):
            print(f"  {name}")
        return 0
    applied = apply(url)
    if applied:
        for name in applied:
            print(f"Applied {name}")
    else:
        print("Nothing to do.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
