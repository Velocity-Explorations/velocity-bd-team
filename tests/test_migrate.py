from __future__ import annotations

from pathlib import Path

from ledger import migrate
from ledger.db import sqlite_path


def test_migrate_creates_tables_and_is_idempotent(tmp_path: Path) -> None:
    url = f"sqlite:///{(tmp_path / 'm.db').as_posix()}"
    first = migrate.apply(url)
    assert first == ["001_initial.sql", "002_change_requests.sql", "003_judgments.sql"]
    assert migrate.apply(url) == []
    assert migrate.list_tables(url) == ["calls", "change_requests", "judgments", "proposals", "runs", "schema_migrations"]


def test_dialect_tokens_differ() -> None:
    text = "CREATE TABLE t (id INTEGER PRIMARY KEY @@AUTOINCREMENT@@);"
    assert migrate.statements(text, "sqlite") == ["CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT)"]
    assert migrate.statements(text, "postgres") == [
        "CREATE TABLE t (id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY)"
    ]


def test_statements_drop_comment_lines() -> None:
    text = "-- a comment; with a semicolon\nSELECT 1;\n\n-- trailing\n"
    assert migrate.statements(text, "sqlite") == ["SELECT 1"]


def test_sqlite_url_resolution() -> None:
    rel = sqlite_path("sqlite:///data/dev.db")
    assert isinstance(rel, Path) and rel.is_absolute()
    assert rel.parts[-2:] == ("data", "dev.db")
    assert sqlite_path("sqlite:///:memory:") == ":memory:"
    absolute = sqlite_path("sqlite:///C:/tmp/x.db")
    assert isinstance(absolute, Path) and absolute.as_posix().endswith("tmp/x.db")
